-- Zenith Fitness: initial database foundation.
-- Run once in the SQL Editor of the NEW Supabase project.
-- This transaction creates tables and seeds gym/plans only. No Sheets import.
-- Client access is deliberately closed until staff policies are installed.
begin;

create table public.gyms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  timezone text not null default 'Asia/Kolkata',
  created_at timestamptz not null default now()
);

create table public.staff (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  user_id uuid not null references auth.users(id),
  full_name text not null check (length(trim(full_name)) > 0),
  role text not null check (role in ('admin', 'receptionist', 'trainer')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (gym_id, user_id),
  unique (gym_id, id)
);

create table public.members (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  admission_id text not null check (length(trim(admission_id)) > 0),
  device_user_id integer check (device_user_id between 1 and 65535),
  full_name text not null check (length(trim(full_name)) > 0),
  phone text not null check (length(trim(phone)) > 0),
  gender text,
  birth_date date,
  legacy_age integer check (legacy_age between 0 and 130),
  category text,
  is_archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (gym_id, admission_id),
  unique (gym_id, device_user_id),
  unique (gym_id, id)
);

-- Separate private details so trainer access need not expose every member field.
create table public.member_private_details (
  member_id uuid primary key,
  gym_id uuid not null references public.gyms(id),
  address text,
  medical_history text,
  remarks text,
  updated_at timestamptz not null default now(),
  foreign key (gym_id, member_id) references public.members(gym_id, id)
);

create table public.membership_plans (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  code text not null,
  name text not null,
  duration_days integer check (duration_days > 0),
  is_active boolean not null default true,
  unique (gym_id, code),
  unique (gym_id, id)
);

-- One row per admission/renewal period; preserve history rather than overwrite.
create table public.memberships (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  member_id uuid not null,
  plan_id uuid not null,
  kind text not null check (kind in ('admission', 'renewal')),
  start_date date not null,
  end_date date not null,
  status text not null default 'confirmed'
    check (status in ('confirmed', 'cancelled')),
  total_amount numeric(12,2) not null check (total_amount >= 0),
  discount_amount numeric(12,2) not null default 0
    check (discount_amount >= 0 and discount_amount <= total_amount),
  final_amount numeric(12,2) generated always as
    (total_amount - discount_amount) stored,
  currency text not null default 'INR' check (currency = 'INR'),
  source_key text,
  created_at timestamptz not null default now(),
  check (end_date >= start_date),
  foreign key (gym_id, member_id) references public.members(gym_id, id),
  foreign key (gym_id, plan_id) references public.membership_plans(gym_id, id),
  unique (gym_id, source_key),
  unique (gym_id, id)
);

-- Payments are a separate ledger. Balances will be calculated from this ledger.
create table public.payments (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  membership_id uuid not null,
  amount numeric(12,2) not null check (amount > 0),
  kind text not null default 'payment' check (kind in ('payment', 'refund')),
  payment_mode text not null,
  paid_at timestamptz not null,
  reference text,
  recorded_by uuid,
  source_key text,
  created_at timestamptz not null default now(),
  foreign key (gym_id, membership_id) references public.memberships(gym_id, id),
  foreign key (gym_id, recorded_by) references public.staff(gym_id, id),
  unique (gym_id, source_key)
);

create table public.trainer_assignments (
  gym_id uuid not null references public.gyms(id),
  trainer_id uuid not null,
  member_id uuid not null,
  assigned_at timestamptz not null default now(),
  primary key (gym_id, trainer_id, member_id),
  foreign key (gym_id, trainer_id) references public.staff(gym_id, id),
  foreign key (gym_id, member_id) references public.members(gym_id, id)
);

-- Keep the raw device identifier even when the member mapping is unknown.
-- source_key will be generated by the importer/bridge to deduplicate retries.
create table public.attendance (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  member_id uuid,
  device_user_id text not null,
  device_identifier text not null,
  punched_at timestamptz not null,
  access_result text not null default 'unknown'
    check (access_result in ('allowed', 'restricted', 'unknown')),
  source_key text not null,
  created_at timestamptz not null default now(),
  foreign key (gym_id, member_id) references public.members(gym_id, id),
  unique (gym_id, source_key)
);

create table public.enquiries (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  full_name text not null,
  phone text not null,
  interested_plan text,
  follow_up_date date,
  status text not null default 'new'
    check (status in ('new', 'contacted', 'converted', 'closed')),
  notes text,
  source_key text,
  created_at timestamptz not null default now(),
  unique (gym_id, source_key)
);

-- Server-managed queues and logs; browser clients will not write these directly.
create table public.sync_jobs (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  destination text not null check (destination in ('google_sheets', 'fingerprint')),
  event_type text not null,
  deduplication_key text not null,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'completed', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (gym_id, destination, deduplication_key)
);

create table public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms(id),
  actor_user_id uuid,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index members_phone_idx on public.members(gym_id, phone);
create index memberships_member_dates_idx
  on public.memberships(gym_id, member_id, end_date desc);
create index payments_membership_idx on public.payments(gym_id, membership_id);
create index attendance_member_time_idx
  on public.attendance(gym_id, member_id, punched_at desc);
create index attendance_time_idx on public.attendance(gym_id, punched_at desc);
create index trainer_assignments_member_idx
  on public.trainer_assignments(gym_id, member_id);
create index sync_jobs_pending_idx on public.sync_jobs(status, available_at);
create index audit_logs_gym_time_idx on public.audit_logs(gym_id, created_at desc);

-- Explicit grants avoid relying on project-specific Supabase defaults.
-- No client grants/policies yet: the publishable key cannot access gym data.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'gyms', 'staff', 'members', 'member_private_details', 'membership_plans',
    'memberships', 'payments', 'trainer_assignments', 'attendance', 'enquiries',
    'sync_jobs', 'audit_logs'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all privileges on table public.%I from public, anon, authenticated', table_name);
    execute format('grant select, insert, update, delete on table public.%I to service_role', table_name);
  end loop;
end $$;

